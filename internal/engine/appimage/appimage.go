package appimage

import (
	"context"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/FuadTesfaye/layerpilot/internal/domain"
	"github.com/FuadTesfaye/layerpilot/internal/runner"
)

// Engine implements direct sandboxed execution for AppImage packages
type Engine struct {
	runner runner.Runner
}

// New creates a new AppImage engine
func New(r runner.Runner) *Engine {
	return &Engine{runner: r}
}

func (e *Engine) ID() string {
	return "appimage"
}

func (e *Engine) Name() string {
	return "AppImage Direct Engine"
}

func (e *Engine) Probe(ctx context.Context, host *domain.HostProfile) (*domain.CapabilityReport, error) {
	rep := &domain.CapabilityReport{
		EngineID:               e.ID(),
		EngineName:             e.Name(),
		SupportedFormats:       []domain.PackageFormat{domain.FormatAppImage},
		SupportedArchitectures: []string{"amd64", "arm64", "386"},
		SupportsGUI:            true,
		Rootless:               true,
		DiagnosticDetails:      make(map[string]string),
	}

	if host.OS != "linux" {
		rep.Available = false
		rep.MissingPrerequisites = append(rep.MissingPrerequisites, "AppImage direct execution is only supported on Linux hosts")
		return rep, nil
	}

	rep.Available = true
	if host.FUSESupport {
		rep.DiagnosticDetails["fuse"] = "Kernel FUSE (/dev/fuse) available"
	} else {
		rep.DiagnosticDetails["fuse"] = "Kernel FUSE not detected; runtime extraction will be used"
	}

	return rep, nil
}

func (e *Engine) Plan(ctx context.Context, plan *domain.InstallPlan) error {
	destDir := filepath.Join(os.Getenv("HOME"), ".local", "share", "compat", "apps", plan.AppID)
	destPath := filepath.Join(destDir, "app.AppImage")
	binPath := filepath.Join(os.Getenv("HOME"), ".local", "share", "compat", "bin", plan.AppID)

	plan.Steps = []domain.PlanStep{
		{
			Order:       1,
			Name:        "StageAppImage",
			Description: fmt.Sprintf("Copy AppImage to %s and mark executable", destPath),
			HostImpact:  fmt.Sprintf("Allocates %d bytes in user home directory", plan.Package.SizeBytes),
		},
		{
			Order:       2,
			Name:        "CreateLauncher",
			Description: fmt.Sprintf("Generate launcher wrapper in %s", binPath),
			HostImpact:  "Registers command in user bin directory",
		},
	}

	plan.HostChanges = []string{
		fmt.Sprintf("Application binary: %s", destPath),
		fmt.Sprintf("Launcher script: %s", binPath),
	}

	return nil
}

func (e *Engine) Apply(ctx context.Context, plan *domain.InstallPlan) error {
	destDir := filepath.Join(os.Getenv("HOME"), ".local", "share", "compat", "apps", plan.AppID)
	if err := os.MkdirAll(destDir, 0755); err != nil {
		return domain.WrapError(domain.ErrCodeRunnerFailed, "failed to create app directory", err)
	}

	destPath := filepath.Join(destDir, "app.AppImage")

	// Copy file safely
	srcFile, err := os.Open(plan.Package.Path)
	if err != nil {
		return domain.WrapError(domain.ErrCodePackageInvalid, "cannot open source AppImage", err)
	}
	defer srcFile.Close()

	destFile, err := os.OpenFile(destPath, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0755)
	if err != nil {
		return domain.WrapError(domain.ErrCodeRunnerFailed, "cannot create destination AppImage", err)
	}
	defer destFile.Close()

	if _, err := io.Copy(destFile, srcFile); err != nil {
		return domain.WrapError(domain.ErrCodeRunnerFailed, "failed copying AppImage data", err)
	}

	// Create wrapper
	binDir := filepath.Join(os.Getenv("HOME"), ".local", "share", "compat", "bin")
	_ = os.MkdirAll(binDir, 0755)
	wrapperPath := filepath.Join(binDir, plan.AppID)

	script := fmt.Sprintf(`#!/bin/sh
# Generated by compat application manager
if [ ! -c /dev/fuse ]; then
    export APPIMAGE_EXTRACT_AND_RUN=1
fi

FLAGS=""
# If running under Wayland, apply GPU & display server compatibility flags
if [ -n "$WAYLAND_DISPLAY" ]; then
    FLAGS="--ozone-platform-hint=auto --disable-gpu"
fi

exec "%s" $FLAGS "$@"
`, destPath)

	if err := os.WriteFile(wrapperPath, []byte(script), 0755); err != nil {
		return domain.WrapError(domain.ErrCodeRunnerFailed, "failed writing wrapper script", err)
	}

	return nil
}

func (e *Engine) Launch(ctx context.Context, app *domain.ApplicationRecord, args []string) error {
	destPath := filepath.Join(os.Getenv("HOME"), ".local", "share", "compat", "apps", app.AppID, "app.AppImage")
	if _, err := os.Stat(destPath); err != nil {
		return domain.NewError(domain.ErrCodeAppNotFound, "AppImage binary not found: "+destPath, "Reinstall the application", "Launch failed")
	}

	env := os.Environ()
	if _, err := os.Stat("/dev/fuse"); err != nil {
		env = append(env, "APPIMAGE_EXTRACT_AND_RUN=1")
	}

	launchArgs := args
	if os.Getenv("WAYLAND_DISPLAY") != "" && app.PackageType == domain.PackageTypeGUI {
		hasOzone := false
		hasDisableGPU := false
		for _, a := range args {
			if strings.Contains(a, "ozone-platform") {
				hasOzone = true
			}
			if strings.Contains(a, "disable-gpu") {
				hasDisableGPU = true
			}
		}
		var extra []string
		if !hasOzone {
			extra = append(extra, "--ozone-platform-hint=auto")
		}
		if !hasDisableGPU {
			extra = append(extra, "--disable-gpu")
		}
		launchArgs = append(extra, launchArgs...)
	}

	cmd := exec.CommandContext(ctx, destPath, launchArgs...)
	cmd.Env = env
	cmd.Stdin = os.Stdin
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

func (e *Engine) Uninstall(ctx context.Context, app *domain.ApplicationRecord) error {
	appDir := filepath.Join(os.Getenv("HOME"), ".local", "share", "compat", "apps", app.AppID)
	_ = os.RemoveAll(appDir)

	binPath := filepath.Join(os.Getenv("HOME"), ".local", "share", "compat", "bin", app.AppID)
	_ = os.Remove(binPath)

	return nil
}

func (e *Engine) Status(ctx context.Context, app *domain.ApplicationRecord) (domain.LifecycleState, error) {
	destPath := filepath.Join(os.Getenv("HOME"), ".local", "share", "compat", "apps", app.AppID, "app.AppImage")
	if _, err := os.Stat(destPath); err == nil {
		return domain.StateInstalled, nil
	}
	return domain.StateRemoved, nil
}

func (e *Engine) Logs(ctx context.Context, app *domain.ApplicationRecord, lines int) ([]string, error) {
	return []string{"AppImage runs directly on host; inspect standard terminal output"}, nil
}
